# ⚠️ **兩個無資料值的處置不對稱，因為歧義程度不同：**
#    `0` 不可能是真實年齡 → 任何屆別都是無資料，不需要具名。
#    `99` 落在合法年齡值域內 → 只在具名的屆別是無資料，否則將來真有 99 歲
#    候選人時他的年齡會被默默吃掉。
