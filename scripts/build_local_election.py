# ---- 年齡的無資料值 ----
#
# 壓縮檔內的官方格式文件 votedata/voteData/選舉資料庫格式.odt 對 elcand.csv
# 的年齡欄寫著：「年齡 Num(3) (部分選舉未必有資料，可能 0 或 99)」，
